const DIFFUSE_REGEX =
  /hunter-gatherer|hunters|foraging|farmers|nomads|nomadic|tribes|cultures?|peoples|aboriginal|siberians|khoisan|khoiasan|bantu|bantou|tungus|thule|inuit|saami|sámi|ainu|papuan|austronesian|polynesian|fishers|fichers|pastoralists|gatherers|archeological|complex|berbers|aryans|tibetans|arameans|alans|vazimba|samoy[eè]des|minor states|anishinabewaki|d[ëe]n[ée]ndeh|denendeh|o[čc]h[ée]thi|guarani|\bcree\b|t'atsaot'ine|blackfoot|niits[ií]tpiis|\bute\b|comanche|o-ga-xpa|osage/i;

const IGNORED_NAMES = new Set(['true', 'false', 'antarctica', 'unclaimed', 'null', '']);

export function isIgnoredPolity(name: string | null | undefined): boolean {
  if (!name) return true;
  return IGNORED_NAMES.has(name.trim().toLowerCase());
}

export function isDiffuseCulture(
  rawName: string | null | undefined,
  rawGroup?: string | null,
): boolean {
  return DIFFUSE_REGEX.test(rawName || '') || DIFFUSE_REGEX.test(rawGroup || '');
}

function hashString(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

const POLITY_ENTRIES = Object.entries(POLITY_DICT);

function normalizeMojibakePolity(raw: string): string {
  return raw
    .replace(/Monte Alb\uFFFDn/g, 'Monte Albán')
    .replace(/Teotihuac\uFFFDn/g, 'Teotihuacán')
    .trim();
}

function findEntryByName(candidate: string): PolityEntry | undefined {
  if (!candidate) return undefined;
  if (POLITY_DICT[candidate]) return POLITY_DICT[candidate];
  const lower = candidate.toLowerCase();
  for (const [key, entry] of POLITY_ENTRIES) {
    if (key.toLowerCase() === lower) return entry;
  }
  return undefined;
}

function lookupExactOrStripped(raw: string): PolityEntry | undefined {
  const direct = findEntryByName(raw);
  if (direct) return direct;

  const lower = raw.toLowerCase();
  if (lower.startsWith('anishinabewaki')) return POLITY_DICT.Anishinabewaki;
  if (lower.startsWith('niitsítpiis') || lower.startsWith('niitsitpiis')) return POLITY_DICT.Blackfoot;
  if (lower.startsWith('o-ga-xpa')) return POLITY_DICT['O-ga-xpa'];

  // Extract parenthetical aliases like "... (Osage)" or "(Blackfoot / Niitsítapi ...)"
  for (const match of raw.matchAll(/\(([^)]+)\)/g)) {
    for (const part of match[1].split('/')) {
      const parenEntry = findEntryByName(part.trim());
      if (parenEntry) return parenEntry;
    }
  }

  const stripped = raw
    .replace(/\s*\([^)]*\)\s*/g, '')
    .replace(/^(Kingdom|Empire|Republic|Sultanate|Khanate|Duchy|Principality|Dynasty)\s+of\s+/i, '')
    .trim();
  if (stripped && stripped !== raw) {
    return findEntryByName(stripped);
  }
  return undefined;
}

function sanitizeFallbackLabel(str: string): string {
  const cleaned = str
    .replace(/\uFFFD/g, '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\u0020-\u01FF\u2000-\u206F\u3000-\u303F\u4E00-\u9FFF\uFF00-\uFFEF]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return cleaned || '地方族群';
}

export function getPolityDisplay(
  rawName: string | null | undefined,
  rawGroup?: string | null,
): { zhName: string; enName: string; color: string; isDiffuse: boolean } {
  const enName = normalizeMojibakePolity(rawName || rawGroup || '未知政权');
  const groupKey = normalizeMojibakePolity(rawGroup || rawName || enName);
  const diffuse = isDiffuseCulture(enName, groupKey);

  const nameEntry = lookupExactOrStripped(enName);
  const groupEntry = lookupExactOrStripped(groupKey);

  const color = diffuse
    ? '#C9BEA6'
    : groupEntry?.color ||
      nameEntry?.color ||
      FALLBACK_PALETTE[hashString(groupKey) % FALLBACK_PALETTE.length];

  const zhName = nameEntry?.zh || sanitizeFallbackLabel(enName);
  return { zhName, enName, color, isDiffuse: diffuse };
}
