export function findNearestTechBenchmark(year: number): TechProgressBenchmark {
  let best = TECH_PROGRESS_BENCHMARKS[0];
  let bestDist = Math.abs(year - best.year);
  for (const item of TECH_PROGRESS_BENCHMARKS) {
    const dist = Math.abs(year - item.year);
    if (dist < bestDist) {
      best = item;
      bestDist = dist;
    }
  }
  return best;
}
